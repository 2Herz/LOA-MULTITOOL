    double GetGemTypeFactor(std::string_view kind) noexcept
    {
        const auto found{ std::ranges::find(GEM_TYPE_FACTORS, kind, &KeyedValue::m_key) };   // 종류가 같은 항목 검색
        return found != GEM_TYPE_FACTORS.end() ? found->m_value : 1.0;   // 없으면 계수 1
    }

    // 무기 공격력 → 보정한 W0 ((툴팁 공격력 + 보정) × W0 보정, 공격력을 모르면 0)
    double GetWeaponBase(double weaponAttack) noexcept
    {
        return weaponAttack > 0.0 ? (weaponAttack + WEAPON_ATTACK_EXTRA) * W0_CALIBRATION : 0.0;   // 공격력을 모르면 0
    }

    // 완갑 재련 단계의 능력치 (등급 표에서 찾음, 0 ~ 25 밖이면 nullptr)
    const VambraceStep* FindVambraceStep(int step) noexcept
    {
        for (const VambraceGrade& grade : VAMBRACE_GRADES)   // 등급 표를 차례로 확인
        {
            const int index{ step - grade.m_firstStep };   // 등급 첫 단계 기준 칸 번호
            if (index >= 0 && static_cast<std::size_t>(index) < grade.m_steps.size()) return &grade.m_steps[static_cast<std::size_t>(index)];   // 범위 안이면 그 칸 주소
        }
        return nullptr;   // 어느 등급에도 없으면 nullptr
    }

    // 문구 키 표에서 키로 값 찾기 (없으면 nullptr)
    const KeyedValue* FindKeyed(std::span<const KeyedValue> table, std::string_view key) noexcept
    {
        const auto found{ std::ranges::find(table, key, &KeyedValue::m_key) };   // 키가 같은 항목 검색
        return found != table.end() ? &*found : nullptr;   // 찾았으면 주소, 없으면 nullptr
    }
