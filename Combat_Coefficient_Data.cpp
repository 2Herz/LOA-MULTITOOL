    // 완갑 재련 단계의 능력치 (등급 표에서 찾음, 0 ~ 25 밖이면 nullptr)
    const VambraceStep* FindVambraceStep(int step) noexcept
    {
        for (const VambraceGrade& grade : VAMBRACE_GRADES)
        {
            const int index{ step - grade.m_firstStep };
            if (index >= 0 && static_cast<std::size_t>(index) < grade.m_steps.size()) return &grade.m_steps[static_cast<std::size_t>(index)];
        }
        return nullptr;
    }

